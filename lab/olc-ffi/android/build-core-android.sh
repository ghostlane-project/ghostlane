#!/usr/bin/env bash
# build-core-android.sh <xray-rust checkout> <lab dir>
#
# The Rust side of the Android lab (lab/olc-ffi/android):
#   - ghostlane-core, the one native library that carries both clients
#     (olc-ffi, the olcRTC client's UniFFI API, and xray-ffi) on one Tokio
#     runtime and one allocator, as libghostlane_core.so for
#     aarch64-linux-android (the shipped ABI) and x86_64-linux-android (the
#     emulator), with the workspace's release profile as it is (the shipped
#     one: thin LTO, one codegen unit, symbols stripped);
#   - linked by the NDK the app pins (androidApp/build.gradle.kts
#     ndkVersion, the release workflow's ANDROID_NDK_VERSION) at the app's
#     minSdk (23), with 16 KiB pages asked for as the app's own cores are
#     (-z max-page-size=16384), and each LOAD segment checked;
#   - the UniFFI Kotlin bindings, generated by olc-ffi's own uniffi-bindgen
#     in library mode from the same build's static archive (it keeps the
#     metadata symbols the stripped .so has lost), into
#     <lab>/core/uniffi.
# The .so files land in <lab>/core/jniLibs/<abi>/. Lines starting BUILD,
# ALIGN, SIZE and SIGNATURE are the job summary's.
set -euo pipefail

src="$(cd "${1:?usage: build-core-android.sh <xray-rust checkout> <lab dir>}" && pwd)"
lab="$(cd "${2:?usage: build-core-android.sh <xray-rust checkout> <lab dir>}" && pwd)"
: "${ANDROID_NDK_VERSION:?the NDK the app pins}"
: "${ANDROID_HOME:?the Android SDK}"
api=23
ndk="$ANDROID_HOME/ndk/$ANDROID_NDK_VERSION"
bin="$ndk/toolchains/llvm/prebuilt/linux-x86_64/bin"
[ -x "$bin/clang" ] || { echo "no NDK $ANDROID_NDK_VERSION at $ndk" >&2; exit 1; }
export ANDROID_NDK_HOME="$ndk" ANDROID_NDK_ROOT="$ndk"
export CARGO_TERM_COLOR=never CARGO_INCREMENTAL=0 CARGO_NET_RETRY=5
page="-C link-arg=-Wl,-z,max-page-size=16384 -C link-arg=-Wl,-z,common-page-size=16384"

out="$lab/core/jniLibs"
rm -rf "$out"
for pair in aarch64-linux-android:arm64-v8a x86_64-linux-android:x86_64; do
  target=${pair%%:*}
  abi=${pair#*:}
  up=$(echo "$target" | tr 'a-z-' 'A-Z_')
  low=$(echo "$target" | tr '-' '_')
  export "CARGO_TARGET_${up}_LINKER=$bin/${target}${api}-clang"
  export "CARGO_TARGET_${up}_RUSTFLAGS=$page"
  export "CC_${low}=$bin/${target}${api}-clang" "CXX_${low}=$bin/${target}${api}-clang++" "AR_${low}=$bin/llvm-ar"
  start=$(date +%s)
  (cd "$src" && cargo build --locked --release -p ghostlane-core --target "$target")
  so="$src/target/$target/release/libghostlane_core.so"
  test -f "$so" || { echo "cargo left no $so" >&2; exit 1; }
  mkdir -p "$out/$abi"
  cp "$so" "$out/$abi/libghostlane_core.so"
  echo "BUILD ghostlane-core $target (API $api, NDK $ANDROID_NDK_VERSION): $(( $(date +%s) - start )) s"

  # Every LOAD segment 16 KiB-aligned (Android 15's page size), as the
  # release workflow checks the app's own cores.
  "$bin/llvm-readelf" -lW "$out/$abi/libghostlane_core.so" > "$lab/core/readelf-$abi.txt"
  aligns=$(awk '$1 == "LOAD" { print $NF }' "$lab/core/readelf-$abi.txt" | tr '\n' ' ')
  [ -n "$aligns" ] || { echo "no LOAD segment in $abi" >&2; exit 1; }
  for a in $aligns; do
    [ $(( a % 16384 )) -eq 0 ] || { echo "ALIGN $abi: a LOAD segment aligned $a, under 16 KiB" >&2; exit 1; }
  done
  echo "ALIGN $abi: every LOAD segment 16 KiB-aligned ($aligns)"

  # As built (the release profile strips the symbols), and what llvm-strip
  # --strip-all would still take off.
  size=$(wc -c < "$out/$abi/libghostlane_core.so" | tr -d ' ')
  "$bin/llvm-strip" --strip-all -o "$lab/core/stripped-$abi.so" "$out/$abi/libghostlane_core.so"
  stripped=$(wc -c < "$lab/core/stripped-$abi.so" | tr -d ' ')
  gz=$(gzip -9 -c "$out/$abi/libghostlane_core.so" | wc -c | tr -d ' ')
  dyn=$("$bin/llvm-nm" -D --defined-only "$out/$abi/libghostlane_core.so" | awk '{print $NF}')
  echo "SIZE $abi: $size bytes as built, $stripped after llvm-strip --strip-all, $gz gzip -9; exports: $(echo "$dyn" | grep -c '^uniffi_olc_ffi_fn_') uniffi functions, $(echo "$dyn" | grep -c '^xray_') xray"
  "$bin/llvm-size" -A -d "$out/$abi/libghostlane_core.so" \
    | awk -v abi="$abi" '$1 ~ /^\.(text|rodata|data\.rel\.ro|eh_frame|eh_frame_hdr|gcc_except_table|dynsym|dynstr|data|bss)$/ { print "SECTION " abi " " $1 " " $2 }'
  "$bin/llvm-readelf" -dW "$out/$abi/libghostlane_core.so" | awk '/NEEDED/ { print "NEEDED '"$abi"' " $NF }'
done

# The Kotlin bindings, from the x86_64 build's static archive.
(cd "$src" && cargo build --locked -p olc-ffi --features bindgen --bin uniffi-bindgen)
gen="$lab/core/uniffi"
rm -rf "$gen"
mkdir -p "$gen"
(cd "$src" && target/debug/uniffi-bindgen generate --library "target/x86_64-linux-android/release/libghostlane_core.a" \
  --language kotlin --out-dir "$gen")
kt=$(find "$gen" -name '*.kt' | head -1)
[ -n "$kt" ] || { echo "no Kotlin bindings in $gen" >&2; exit 1; }
echo "BINDINGS $(find "$gen" -name '*.kt' | sed "s#$gen/##" | tr '\n' ' ')($(wc -l < "$kt" | tr -d ' ') lines)"
# The two callbacks the Android service implements today, as gomobile
# declares them (mobile.SocketProtector, mobile.LogWriter).
for sig in 'fun `protect`(`fd`: kotlin.Long): kotlin.Boolean' 'fun `writeLog`(`msg`: kotlin.String)'; do
  if grep -qF "$sig" "$kt"; then echo "SIGNATURE ok: $sig"; else echo "SIGNATURE differs: $sig"; grep -n 'fun `protect`\|fun `writeLog`\|fun protect\|fun writeLog' "$kt" || true; fi
done
