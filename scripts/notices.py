#!/usr/bin/env python3
"""THIRD_PARTY_NOTICES.md, the Rust part, generated from the lock files (K10).

  scripts/notices.py generate [--core-lock FILE] [--pin SHA]   rewrite the generated block
  scripts/notices.py check    [--core-lock FILE] [--pin SHA]   exit 1 when the file differs
  scripts/notices.py fill     [--core-lock FILE] [--pin SHA] [--registry DIR] [--core-tree DIR]
                                                               add the licences the table lacks

The locks read:
  - the app's own: every Cargo.lock under the repository (today cli/Cargo.lock);
  - the Rust core's, at the pin the app reads (scripts/ghostlane-core-pin.sh, or --pin):
    fetched from the fork at that commit, or --core-lock FILE for a copy.

The block between the two marker lines of THIRD_PARTY_NOTICES.md is the only
text this script writes; the words around it are by hand. Licences come from
scripts/notices-licences.json, keyed by crate name (and by "name@version" where
versions differ). A crate in a lock with no licence in the table fails both
generate and check: run `fill`, read what it added, commit it. The table is
never consulted for a crate that is not in a lock, and an entry nobody uses is
dropped by `fill --prune`.
Python 3.11+, standard library only.
"""
import argparse
import json
import os
import re
import subprocess
import sys
import tomllib
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NOTICES = os.path.join(ROOT, "THIRD_PARTY_NOTICES.md")
TABLE = os.path.join(ROOT, "scripts", "notices-licences.json")
PIN_FILE = os.path.join(ROOT, "scripts", "ghostlane-core-pin.sh")
BEGIN = "<!-- notices:begin (generated by scripts/notices.py; do not edit) -->"
END = "<!-- notices:end -->"
# A crate of the core's own workspace (a path package) is MPL-2.0, the core's licence;
# the vendored copies of other people's crates carry their own, found by `fill`.
UA = "ghostlane-notices"


def read_pin():
    text = open(PIN_FILE).read()
    repo = re.search(r'GHOSTLANE_CORE_REPO="\$\{GHOSTLANE_CORE_REPO:-([^}]+)\}"', text).group(1)
    commit = re.search(r"^GHOSTLANE_CORE_COMMIT=([0-9a-f]{40})$", text, re.M).group(1)
    return repo, commit


def fetch_core_lock(repo, commit):
    url = f"https://raw.githubusercontent.com/{repo}/{commit}/Cargo.lock"
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode()


def parse_lock(text):
    """[(name, version, kind)] with kind registry | git | path."""
    out = []
    for p in tomllib.loads(text).get("package", []):
        src = p.get("source", "")
        kind = src.split("+")[0] if src else "path"
        out.append((p["name"], p["version"], kind))
    return out


def app_locks():
    found = []
    for base, dirs, files in os.walk(ROOT):
        dirs[:] = sorted(d for d in dirs if d not in (".git", "node_modules", "build", "target"))
        if "Cargo.lock" in files:
            found.append(os.path.relpath(os.path.join(base, "Cargo.lock"), ROOT))
    return sorted(found)


def load_table():
    with open(TABLE) as f:
        return json.load(f)


def licence_of(table, name, version):
    return table.get(f"{name}@{version}") or table.get(name)


def normalise(expr):
    expr = expr.strip().replace("/", " OR ")
    return re.sub(r"\s+", " ", expr)


def section(title, intro, pkgs, table, missing):
    by_name = {}
    for name, version, _ in pkgs:
        by_name.setdefault(name, set()).add(version)
    rows = []
    for name in sorted(by_name):
        versions = sorted(by_name[name], key=lambda v: [int(x) if x.isdigit() else x for x in re.split(r"[.+-]", v)])
        lics = {licence_of(table, name, v) for v in versions}
        if None in lics:
            missing.append(name)
            continue
        rows.append(f"| {name} | {', '.join(versions)} | {' ; '.join(sorted(lics))} |")
    return "\n".join([f"### {title}", "", intro, "", "| Crate | Versions | Licence |", "| --- | --- | --- |", *rows, ""])


def build(core_text, repo, commit):
    table = load_table()
    missing = []
    parts = [BEGIN, "", "## Rust crates, from the lock files", "",
             "Generated by `scripts/notices.py` from the lock files named below; `scripts/notices-licences.json` "
             "holds the licence of each crate, and a CI check (`notices.yml`, K10) fails when this block differs "
             "from the locks. A crate whose licence is an `OR` choice is used under any one of its options.", ""]
    for lock in app_locks():
        pkgs = parse_lock(open(os.path.join(ROOT, lock)).read())
        parts.append(section(f"`{lock}`", f"{len(pkgs)} packages: the application's own Rust build.", pkgs, table, missing))
    pkgs = parse_lock(core_text)
    parts.append(section(
        f"The Rust core, `Cargo.lock` of {repo} at `{commit[:12]}`",
        f"{len(pkgs)} packages, the pin in `scripts/ghostlane-core-pin.sh`: the engine and the extension's core "
        "(xray-rust's own crates are MPL-2.0; vendored crates keep their own licence).",
        pkgs, table, missing))
    parts.append(END)
    if missing:
        sys.exit("no licence in scripts/notices-licences.json for: " + ", ".join(sorted(set(missing))) + "\n(run: scripts/notices.py fill)")
    return "\n".join(parts)


def splice(current, block):
    if BEGIN not in current or END not in current:
        sys.exit("THIRD_PARTY_NOTICES.md lacks the notices:begin / notices:end markers")
    head, rest = current.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + block + tail


def core_lock_text(args):
    repo, commit = read_pin()
    if args.pin:
        commit = args.pin
    if args.core_lock:
        return open(args.core_lock).read(), repo, commit
    return fetch_core_lock(repo, commit), repo, commit


def licence_from_toml(text):
    d = tomllib.loads(text)
    pkg = d.get("package", {})
    lic = pkg.get("license")
    if isinstance(lic, dict):  # license.workspace = true
        return None
    return normalise(lic) if lic else None


def find_registry_licence(registry, name, version):
    if registry and os.path.isdir(registry):
        for src in sorted(os.listdir(registry)):
            p = os.path.join(registry, src, f"{name}-{version}", "Cargo.toml")
            if os.path.exists(p):
                return licence_from_toml(open(p).read())
    return None


def crates_io_licence(name, version):
    req = urllib.request.Request(f"https://crates.io/api/v1/crates/{name}/{version}", headers={"User-Agent": UA})
    import time
    time.sleep(1.1)
    with urllib.request.urlopen(req, timeout=60) as r:
        return normalise(json.load(r)["version"]["license"] or "")


def fill(args):
    text, repo, commit = core_lock_text(args)
    packs = [(p, "core") for p in parse_lock(text)]
    for lock in app_locks():
        packs += [(p, lock) for p in parse_lock(open(os.path.join(ROOT, lock)).read())]
    table = load_table()
    registry = args.registry or os.path.expanduser("~/.cargo/registry/src")
    added = []
    for (name, version, kind), _ in packs:
        if licence_of(table, name, version):
            continue
        lic = None
        if kind == "path" and args.core_tree:
            for rel in (f"vendor/{name}", f"olc/vendor/{name}-{version}", f"olc/{name}", f"crates/{name}"):
                p = os.path.join(args.core_tree, rel, "Cargo.toml")
                if os.path.exists(p):
                    lic = licence_from_toml(open(p).read())
                    break
            if lic is None:
                lic = "MPL-2.0"
        elif kind == "registry":
            lic = find_registry_licence(registry, name, version) or crates_io_licence(name, version)
        if not lic:
            print(f"cannot find a licence for {name} {version} ({kind}): add it by hand", file=sys.stderr)
            continue
        table.setdefault(name, lic)
        if table[name] != lic:
            table[f"{name}@{version}"] = lic
        added.append(f"{name} {version}: {lic}")
    if args.prune:
        used = {n for (n, _, _), _ in packs}
        table = {k: v for k, v in table.items() if k.split("@")[0] in used}
    with open(TABLE, "w") as f:
        json.dump(dict(sorted(table.items())), f, indent=1, sort_keys=False)
        f.write("\n")
    print("\n".join(added) or "nothing to add")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["generate", "check", "fill"])
    ap.add_argument("--core-lock")
    ap.add_argument("--pin")
    ap.add_argument("--registry")
    ap.add_argument("--core-tree")
    ap.add_argument("--prune", action="store_true")
    args = ap.parse_args()
    if args.cmd == "fill":
        return fill(args)
    text, repo, commit = core_lock_text(args)
    new = splice(open(NOTICES).read(), build(text, repo, commit))
    if args.cmd == "generate":
        open(NOTICES, "w").write(new)
        print("THIRD_PARTY_NOTICES.md written")
        return
    if new != open(NOTICES).read():
        sys.exit("THIRD_PARTY_NOTICES.md differs from the lock files at the pin: run scripts/notices.py generate")
    print("notices match the lock files")


if __name__ == "__main__":
    main()
