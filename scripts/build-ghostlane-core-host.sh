#!/usr/bin/env bash
# build-ghostlane-core-host.sh <output-dir> <rust target>...
#
# Builds ghostlane-core for every target that is not Android (those are
# scripts/build-ghostlane-core-android.sh's), at the pin in
# scripts/ghostlane-core-pin.sh or at GHOSTLANE_CORE_PIN_OVERRIDE (a dispatch's
# pin=<sha>), with the `boring` feature and the workspace's release profile as
# it ships (thin LTO, one codegen unit):
#
#   on a Mac          aarch64-apple-darwin  x86_64-apple-darwin
#                     aarch64-apple-ios     aarch64-apple-ios-sim
#   on Linux x86_64   x86_64-unknown-linux-musl  aarch64-unknown-linux-musl
#                     armv7-unknown-linux-musleabihf
#                     (static; the C and C++ cross compiler is the one
#                     scripts/build-hev-linux.sh --toolchain makes, unless
#                     CC_<target> is already set)
#   on Windows        x86_64-pc-windows-msvc
#
# Per target, under <output-dir>:
#   lib/<target>/libghostlane_core.a   the static library as rustc wrote it
#                                      (ghostlane_core.lib on Windows). An
#                                      archive is never stripped: it is its
#                                      own symbols.
#   bin/<target>/ghostlane-engine      the desktop program, stripped: only
#                                      where the commit has
#                                      crates/ghostlane-engine, and never for
#                                      an iPhone target.
#   symbols/<target>/ghostlane-engine  the same program before the strip.
#   report/<target>.txt                this target's lines of the report.
#   stamps/<target>                    what was built (commit, profile, the
#                                      Rust toolchain, the hash of this
#                                      script): a target whose stamp and
#                                      files are there is kept, and cargo is
#                                      not started for it.
# and once:
#   include/XrayRust/                  xray-ffi's C header and module map (the
#                                      UniFFI side is generated by olc-ffi's
#                                      uniffi-bindgen from a library, as
#                                      scripts/build-ghostlane-core-ios.sh does).
#   report.txt                         every line, each starting with its
#                                      kind: PIN, BUILD, SIZE, BORING, ENGINE,
#                                      LINK, FAILED. A target that fails does
#                                      not stop the others; the script then
#                                      leaves with 1.
#   compiled.txt                       how many crates cargo compiled in this
#                                      run: 0 when every target was kept.
#
# BoringSSL is proven from the built file, not from the command line:
#   build-ghostlane-core-host.sh --boring-proof <library, archive or program>
# reads the file's symbol table and fails unless it defines BoringSSL's own
# SSL_CTX_new and DTLS_method. AWS-LC, which the core links as well, cannot
# pass for it: aws-lc-sys prefixes every symbol with its version and builds no
# libssl. A stripped file has no such table and fails, so the proof is run on
# what was kept before the strip. A target without BoringSSL fails the build.
#
#   build-ghostlane-core-host.sh --stamp <rust target>
# prints the stamp a build of that target would write (the tests read it).
#
# GHOSTLANE_CORE_FAST=1 turns LTO off, for a lab build only.
# GHOSTLANE_CORE_SRC is the checkout of the core (default <output-dir>/src).
# GHOSTLANE_CORE_KEEP_GOING=1 lets cargo go on past a crate that fails, so the
#   report names every crate that does not compile (the Windows leg).
# GHOSTLANE_CORE_LINK_PROOF=1, on a musl target of a commit with no
#   ghostlane-engine: links olc-client with `boring` into a static program and
#   checks it, so that "a static program with BoringSSL links for this target"
#   is known before the engine exists. The program is not kept. It is tried
#   as well when ghostlane-core itself does not compile for the target (which
#   still fails it): the LINK line then says whether BoringSSL is the problem.
# Needs rustup, git, cmake, a C and C++ compiler and libclang (boring-sys's
# bindgen); on Linux also what build-hev-linux.sh --toolchain needs. bash 3.2
# safe (macOS).
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SELF="$HERE/$(basename "${BASH_SOURCE[0]}")"

usage() {
  echo "usage: build-ghostlane-core-host.sh <output-dir> <rust target>..." >&2
  echo "       build-ghostlane-core-host.sh --boring-proof <file>" >&2
  echo "       build-ghostlane-core-host.sh --stamp <rust target>" >&2
  exit 2
}

# The functions only BoringSSL defines under these names in this workspace:
# the context every DTLS and TLS connection of the olcRTC client starts from,
# and the DTLS method itself.
BORING_NAMES="SSL_CTX_new DTLS_method"

# boring_proof <file>: one line saying what was found; 0 when BoringSSL is in
# the file, 1 when it is not, 2 when the file cannot be read.
boring_proof() {
  local file="$1" nm tmp total missing="" n ssl
  [ -f "$file" ] || { echo "no file $file"; return 2; }
  nm="${NM:-}"
  [ -n "$nm" ] || nm="$(command -v llvm-nm || command -v nm || true)"
  [ -n "$nm" ] || { echo "no nm to read $(basename "$file") with"; return 2; }
  tmp="$(mktemp)"
  # Defined functions only (type T or t). Mach-O names carry one more leading
  # underscore than ELF and COFF ones.
  { "$nm" "$file" 2>/dev/null || true; } |
    awk 'NF >= 3 && $(NF - 1) ~ /^[Tt]$/ { print $NF }' | sed 's/^_//' | sort -u > "$tmp"
  total="$(wc -l < "$tmp" | tr -d ' ')"
  for n in $BORING_NAMES; do
    grep -qx "$n" "$tmp" || missing="$missing $n"
  done
  ssl="$(grep -c -E '^(SSL|DTLS)[A-Za-z0-9]*_' "$tmp" || true)"
  rm -f "$tmp"
  if [ -n "$missing" ]; then
    echo "no BoringSSL in $(basename "$file"): $total functions in its symbol table, and none of them is${missing}"
    return 1
  fi
  echo "BoringSSL is in $(basename "$file"): it defines ${BORING_NAMES// / and } ($ssl SSL_ and DTLS functions among $total)"
}

if [ "${1:-}" = "--boring-proof" ]; then
  [ $# -eq 2 ] || usage
  boring_proof "$2"
  exit 0
fi

# shellcheck source=scripts/ghostlane-core-pin.sh
. "$HERE/ghostlane-core-pin.sh"
# A dispatch with pin=<sha> builds another commit of the core: the resolver
# checks it, and an empty value is the pin.
GHOSTLANE_CORE_COMMIT="$(bash "$HERE/ghostlane-core-resolve.sh" "${GHOSTLANE_CORE_PIN_OVERRIDE:-}" |
  sed -n 's/^GHOSTLANE_CORE_COMMIT=//p')"
source_of_commit="the pin"
[ -z "${GHOSTLANE_CORE_PIN_OVERRIDE:-}" ] || source_of_commit="an override of the pin"

profile="shipped"
if [ "${GHOSTLANE_CORE_FAST:-0}" = "1" ]; then
  profile="fast"
  export CARGO_PROFILE_RELEASE_LTO=false CARGO_PROFILE_RELEASE_CODEGEN_UNITS=16
fi

is_musl() { case "$1" in *-linux-musl*) return 0 ;; *) return 1 ;; esac; }
is_ios() { case "$1" in *-apple-ios*) return 0 ;; *) return 1 ;; esac; }
is_windows() { case "$1" in *-windows-*) return 0 ;; *) return 1 ;; esac; }
is_darwin() { case "$1" in *-apple-darwin) return 0 ;; *) return 1 ;; esac; }
lib_name() { if is_windows "$1"; then echo ghostlane_core.lib; else echo libghostlane_core.a; fi; }
exe_name() { if is_windows "$1"; then echo "$2.exe"; else echo "$2"; fi; }

# What decides a build: the commit, the profile, the Rust toolchain (another
# rustc compiles other code from the same commit), this script, and for a musl
# target the script that makes its cross compiler.
stamp_of() {
  local s
  s="$GHOSTLANE_CORE_COMMIT $profile boring rust $GHOSTLANE_CORE_TOOLCHAIN $(git hash-object "$SELF")"
  if is_musl "$1"; then s="$s $(git hash-object "$HERE/build-hev-linux.sh")"; fi
  echo "$s"
}

if [ "${1:-}" = "--stamp" ]; then
  [ $# -eq 2 ] || usage
  stamp_of "$2"
  exit 0
fi

[ $# -ge 2 ] || usage
case "$1" in -*) usage ;; esac
OUT="$1"
shift
mkdir -p "$OUT"
OUT="$(cd "$OUT" && pwd)"
export PATH="$HOME/.cargo/bin:$PATH"
export CARGO_TERM_COLOR=never CARGO_INCREMENTAL=0 CARGO_NET_RETRY=5
# The workspace's release profile strips at the link. Here the program is
# linked with its symbols, kept as it is under symbols/, and stripped as a
# copy: the same code, and a crash can be read.
export CARGO_PROFILE_RELEASE_STRIP=false

mkdir -p "$OUT/report" "$OUT/stamps"

# kept <target>: the stamp is this build's and its files are there.
kept() {
  local target="$1" stamp="$OUT/stamps/$1"
  [ -f "$stamp" ] || return 1
  [ "$(sed -n 1p "$stamp")" = "$(stamp_of "$target")" ] || return 1
  [ -s "$OUT/lib/$target/$(lib_name "$target")" ] || return 1
  [ -s "$OUT/report/$target.txt" ] || return 1
  if [ "$(sed -n 2p "$stamp")" = "engine yes" ]; then
    [ -s "$OUT/bin/$target/$(exe_name "$target" ghostlane-engine)" ] || return 1
    [ -s "$OUT/symbols/$target/$(exe_name "$target" ghostlane-engine)" ] || return 1
  fi
  return 0
}

ALL_TARGETS="$*"
todo=""
kept_lines=""
for target in $ALL_TARGETS; do
  if kept "$target"; then
    kept_lines="${kept_lines}KEPT $target: built before from $GHOSTLANE_CORE_COMMIT ($profile, Rust $GHOSTLANE_CORE_TOOLCHAIN), nothing compiled
"
  else
    todo="$todo $target"
  fi
done

compiled=0
write_report() {
  local t
  {
    echo "PIN $GHOSTLANE_CORE_COMMIT ($source_of_commit, $profile, Rust $GHOSTLANE_CORE_TOOLCHAIN, features: boring)"
    for t in $ALL_TARGETS; do
      [ ! -f "$OUT/report/$t.txt" ] || cat "$OUT/report/$t.txt"
    done
  } > "$OUT/report.txt"
  echo "$compiled" > "$OUT/compiled.txt"
}

printf '%s' "$kept_lines"
if [ -z "$todo" ]; then
  write_report
  echo "COMPILED 0: every target was kept, cargo was not started"
  exit 0
fi

src="${GHOSTLANE_CORE_SRC:-$OUT/src}"
if [ "$(git -C "$src" rev-parse HEAD 2>/dev/null || true)" != "$GHOSTLANE_CORE_COMMIT" ]; then
  rm -rf "$src"
  git init -q "$src"
  git -C "$src" fetch -q --depth 1 "https://github.com/${GHOSTLANE_CORE_REPO}.git" "$GHOSTLANE_CORE_COMMIT"
  git -C "$src" -c advice.detachedHead=false checkout -q FETCH_HEAD
fi
test "$(git -C "$src" rev-parse HEAD)" = "$GHOSTLANE_CORE_COMMIT"

has_engine=no
[ ! -f "$src/crates/ghostlane-engine/Cargo.toml" ] || has_engine=yes
engine_features=""
if [ "$has_engine" = yes ] && grep -Eq '^boring[[:space:]]*=' "$src/crates/ghostlane-engine/Cargo.toml"; then
  engine_features="--features boring"
fi

target_flags=""
for target in $todo; do target_flags="$target_flags --target $target"; done
# shellcheck disable=SC2086
rustup toolchain install "$GHOSTLANE_CORE_TOOLCHAIN" --profile minimal --no-self-update \
  --component rustfmt $target_flags > /dev/null
# bindgen formats boring-sys's bindings with rustfmt, and boring-sys names its
# ErrLib enum by reading that text (see build-ghostlane-core-android.sh). The
# toolchain's own rustfmt, named directly: the rustup proxy fails under
# `cargo +<toolchain>`.
RUSTFMT="$(rustup which --toolchain "$GHOSTLANE_CORE_TOOLCHAIN" rustfmt)"
export RUSTFMT
cargo_="cargo +$GHOSTLANE_CORE_TOOLCHAIN"

logs="$OUT/logs"
mkdir -p "$logs"

# A musl target's C and C++ come from a cross compiler: the caller's
# (CC_<target>) or the one build-hev-linux.sh makes. BoringSSL's C++ runtime
# is then the sysroot's static libstdc++, named so that rustc neither looks
# for the archive itself nor lets the linker take a shared one.
musl_env() {
  local target="$1" low line env_file
  low="$(echo "$target" | tr '-' '_')"
  if [ -z "$(eval "echo \"\${CC_${low}:-}\"")" ]; then
    env_file="$(mktemp)"
    bash "$HERE/build-hev-linux.sh" --toolchain \
      "${GHOSTLANE_MUSL_TOOLCHAIN_DIR:-${TMPDIR:-/tmp}/ghostlane-musl-toolchain}" "$target" > "$env_file"
    while IFS= read -r line; do
      [ -z "$line" ] || export "${line?}"
    done < "$env_file"
    rm -f "$env_file"
  fi
  export "BORING_BSSL_RUST_CPPLIB_${low}=static:-bundle=stdc++"
}

# run_cargo <target> <log> <cargo arguments>...: with the target's own
# environment; the output goes to the log too, where the crates cargo
# compiled are counted at the end.
run_cargo() {
  local target="$1" log="$2" keep="" rc=0
  shift 2
  [ "${GHOSTLANE_CORE_KEEP_GOING:-0}" != "1" ] || keep="--keep-going"
  (
    if is_ios "$target"; then
      export IPHONEOS_DEPLOYMENT_TARGET="${IPHONEOS_DEPLOYMENT_TARGET:-15.0}"
    elif is_darwin "$target"; then
      export MACOSX_DEPLOYMENT_TARGET="${MACOSX_DEPLOYMENT_TARGET:-11.0}"
    fi
    cd "$src"
    # shellcheck disable=SC2086
    $cargo_ build --locked --release $keep --target "$target" "$@"
  ) 2>&1 | tee -a "$log" || rc=$?
  return "$rc"
}

# failed <target> <what> <log>: the crates that did not compile, by name.
failed() {
  local target="$1" what="$2" log="$3" why
  why="$(grep -E '^error: (could not compile|failed to run custom build command)' "$log" |
    sed -e 's/^error: //' | sort -u | tr '\n' ';' | sed -e 's/;$//' -e 's/;/; /g' || true)"
  [ -n "$why" ] || why="see the log"
  echo "FAILED $target: $what: $why" | tee -a "$OUT/report/$target.txt"
}

# static_program <file>: no interpreter, no shared library.
static_program() {
  local file="$1" readelf
  readelf="$(command -v llvm-readelf || command -v readelf)"
  if "$readelf" -lW "$file" | grep -q 'INTERP'; then echo "asks for an interpreter"; return 1; fi
  if "$readelf" -dW "$file" | grep -q 'NEEDED'; then echo "needs a shared library"; return 1; fi
  echo "static"
}

# strip_program <target> <unstripped> <stripped>
strip_program() {
  local target="$1" from="$2" to="$3"
  cp "$from" "$to"
  if is_windows "$target"; then
    return 0 # the symbols of an MSVC program are its .pdb, beside it
  elif is_darwin "$target"; then
    strip "$to"
    codesign --force --sign - "$to" > /dev/null 2>&1 || true
  else
    "$(command -v llvm-strip || command -v strip)" --strip-all "$to"
  fi
}

# link_proof <target>: a musl target of a commit with no ghostlane-engine
# links olc-client with `boring` (no xray crate in it) into a static program,
# which must carry BoringSSL; the LINK line says what it found. The program is
# not kept.
link_proof() {
  local target="$1" start sym rc=0 how proof
  start=$(date +%s)
  if ! run_cargo "$target" "$logs/$target.log" -p olc-client --bin olc-client --features boring; then
    failed "$target" "a static program with boring (olc-client) did not link" "$logs/$target.log"
    return 1
  fi
  sym="$src/target/$target/release/olc-client"
  how="$(static_program "$sym")" || rc=$?
  proof="$(boring_proof "$sym")" || rc=$?
  say "LINK $target: olc-client with boring, standing in for the engine, links in $(($(date +%s) - start)) s: $how, $(wc -c < "$sym" | tr -d ' ') bytes; $proof"
  [ "$rc" -eq 0 ] || { failed "$target" "the stand-in program is not static or carries no BoringSSL" "$logs/$target.log"; return 1; }
}

build_target() {
  local target="$1" start lib name out proof rc exe sym how
  out="$OUT/report/$target.txt"
  : > "$out"
  : > "$logs/$target.log"
  rm -rf "${OUT:?}/lib/${target:?}" "${OUT:?}/bin/${target:?}" "${OUT:?}/symbols/${target:?}" "${OUT:?}/stamps/${target:?}"
  say() { echo "$*" | tee -a "$out"; }
  if is_musl "$target"; then musl_env "$target"; fi

  start=$(date +%s)
  if ! run_cargo "$target" "$logs/$target.log" -p ghostlane-core --features boring; then
    failed "$target" "ghostlane-core with boring did not build" "$logs/$target.log"
    # The target still fails. What the stand-in says is whether BoringSSL
    # itself builds and links into a static program there, apart from the
    # crates that stopped the core.
    if is_musl "$target" && [ "${GHOSTLANE_CORE_LINK_PROOF:-0}" = "1" ]; then
      link_proof "$target" || true
    fi
    return 1
  fi
  name="$(lib_name "$target")"
  lib="$src/target/$target/release/$name"
  test -f "$lib" || { echo "cargo left no $lib" >&2; return 1; }
  mkdir -p "$OUT/lib/$target"
  cp "$lib" "$OUT/lib/$target/$name"
  say "BUILD $target: ghostlane-core in $(($(date +%s) - start)) s"
  say "SIZE $target: $name $(wc -c < "$OUT/lib/$target/$name" | tr -d ' ') bytes"
  rc=0
  proof="$(boring_proof "$OUT/lib/$target/$name")" || rc=$?
  if [ "$rc" -ne 0 ]; then
    say "BORING $target: NOT linked: $proof"
    failed "$target" "the library carries no BoringSSL" "$logs/$target.log"
    return 1
  fi
  say "BORING $target: linked: $proof"

  if [ "$has_engine" = yes ] && ! is_ios "$target"; then
    start=$(date +%s)
    # shellcheck disable=SC2086
    if ! run_cargo "$target" "$logs/$target.log" -p ghostlane-engine $engine_features; then
      failed "$target" "ghostlane-engine did not build" "$logs/$target.log"
      return 1
    fi
    exe="$(exe_name "$target" ghostlane-engine)"
    sym="$OUT/symbols/$target/$exe"
    mkdir -p "$OUT/bin/$target" "$OUT/symbols/$target"
    cp "$src/target/$target/release/$exe" "$sym"
    if is_windows "$target" && [ -f "$src/target/$target/release/ghostlane_engine.pdb" ]; then
      cp "$src/target/$target/release/ghostlane_engine.pdb" "$OUT/symbols/$target/"
    fi
    strip_program "$target" "$sym" "$OUT/bin/$target/$exe"
    say "ENGINE $target: ghostlane-engine${engine_features:+ ($engine_features)} in $(($(date +%s) - start)) s, $(wc -c < "$OUT/bin/$target/$exe" | tr -d ' ') bytes stripped, $(wc -c < "$sym" | tr -d ' ') with its symbols"
    rc=0
    proof="$(boring_proof "$sym")" || rc=$?
    if [ "$rc" -ne 0 ]; then
      say "BORING $target: NOT linked into ghostlane-engine: $proof"
      failed "$target" "ghostlane-engine carries no BoringSSL" "$logs/$target.log"
      return 1
    fi
    say "BORING $target: linked into ghostlane-engine: $proof"
    if is_musl "$target"; then
      rc=0
      how="$(static_program "$sym")" || rc=$?
      say "LINK $target: ghostlane-engine is $how"
      [ "$rc" -eq 0 ] || { failed "$target" "ghostlane-engine is not a static program" "$logs/$target.log"; return 1; }
    fi
  elif is_ios "$target"; then
    say "ENGINE $target: none, a phone links the library"
  else
    say "ENGINE $target: none, this commit has no crates/ghostlane-engine"
    if is_musl "$target" && [ "${GHOSTLANE_CORE_LINK_PROOF:-0}" = "1" ]; then
      link_proof "$target" || return 1
    fi
  fi

  {
    stamp_of "$target"
    if [ -f "$OUT/bin/$target/$(exe_name "$target" ghostlane-engine)" ]; then echo "engine yes"; else echo "engine no"; fi
  } > "$OUT/stamps/$target"
}

# A target that fails does not stop the others: one run says what every
# target does. Each is built in a shell of its own, so that any command that
# fails there ends that target, and its environment does not reach the next.
failures=""
for target in $todo; do
  set +e
  (
    set -e
    build_target "$target"
  )
  rc=$?
  set -e
  [ "$rc" -eq 0 ] || failures="$failures $target"
  compiled=$((compiled + $(grep -c '^ *Compiling ' "$logs/$target.log" || true)))
done

rm -rf "$OUT/include"
mkdir -p "$OUT/include/XrayRust"
cp "$src/crates/xray-ffi/include/xray_ffi.h" "$src/crates/xray-ffi/include/module.modulemap" "$OUT/include/XrayRust/"

write_report
echo "COMPILED $compiled crates in this run"
if [ -n "$failures" ]; then
  echo "not built:$failures" >&2
  exit 1
fi
